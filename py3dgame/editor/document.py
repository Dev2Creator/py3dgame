"""Serialisable scene documents: the spine every editor needs.

A document is plain JSON. Nodes reference built-in meshes and describe materials
and lights by value, so a scene can be saved, diffed, hand-edited or generated by
a tool without instantiating engine objects first.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from ..exceptions import DocumentError
from ..graphics.camera import PerspectiveCamera
from ..graphics.material import Material
from ..graphics.mesh import Mesh
from ..graphics.renderer import SoftwareRenderer
from ..lighting.light import DirectionalLight, PointLight, SpotLight
from ..math3d import Quaternion, Vec3
from ..math3d import Transform as Transform3D

MESHES = {"cube": Mesh.cube, "plane": Mesh.plane, "triangle": Mesh.triangle}
MESH_SIZES = {"cube": 1.6, "plane": 8.0, "triangle": 1.0}


def _vec3(value: Any, field_name: str) -> Tuple[float, float, float]:
    if not isinstance(value, (list, tuple)) or len(value) != 3:
        raise DocumentError(f"{field_name} must be a 3-item list")
    try:
        return (float(value[0]), float(value[1]), float(value[2]))
    except (TypeError, ValueError) as exc:
        raise DocumentError(f"{field_name} must contain numbers") from exc


@dataclass
class NodeDocument:
    id: str
    mesh: str = "cube"
    name: str = ""
    position: Tuple[float, float, float] = (0.0, 0.0, 0.0)
    rotation: Tuple[float, float, float] = (0.0, 0.0, 0.0)
    scale: Tuple[float, float, float] = (1.0, 1.0, 1.0)
    material: Dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.id or not isinstance(self.id, str):
            raise DocumentError("node id must be a non-empty string")
        if self.mesh not in MESHES:
            raise DocumentError(f"unknown mesh {self.mesh!r}; available: {sorted(MESHES)}")
        self.name = self.name or self.id
        self.position = _vec3(self.position, f"{self.id}.position")
        self.rotation = _vec3(self.rotation, f"{self.id}.rotation")
        self.scale = _vec3(self.scale, f"{self.id}.scale")
        if any(v <= 0 for v in self.scale):
            raise DocumentError(f"{self.id}.scale must be positive")
        self.material = dict(self.material or {})
        for key in ("base_colour", "emission"):
            if key in self.material and isinstance(self.material[key], (list, tuple)):
                self.material[key] = tuple(int(c) for c in self.material[key])
        self.build_material()

    def build_material(self) -> Material:
        try:
            return Material(**self.material)
        except (TypeError, ValueError) as exc:
            raise DocumentError(f"{self.id}.material: {exc}") from exc

    def transform(self) -> Transform3D:
        return Transform3D(
            position=Vec3(*self.position),
            rotation=Quaternion.from_euler(*self.rotation),
            scale=Vec3(*self.scale),
        )

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "name": self.name,
            "mesh": self.mesh,
            "position": list(self.position),
            "rotation": list(self.rotation),
            "scale": list(self.scale),
            "material": dict(self.material),
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "NodeDocument":
        if not isinstance(data, dict):
            raise DocumentError("each node must be an object")
        return cls(
            id=str(data.get("id") or ""),
            mesh=str(data.get("mesh") or "cube"),
            name=str(data.get("name") or ""),
            position=data.get("position", (0.0, 0.0, 0.0)),
            rotation=data.get("rotation", (0.0, 0.0, 0.0)),
            scale=data.get("scale", (1.0, 1.0, 1.0)),
            material=data.get("material", {}),
        )


@dataclass
class SceneDocument:
    name: str = "scene"
    camera_position: Tuple[float, float, float] = (4.0, 2.8, 5.2)
    camera_target: Tuple[float, float, float] = (0.0, 0.5, 0.0)
    fov: float = 55.0
    background: Tuple[int, int, int, int] = (18, 20, 30, 255)
    nodes: List[NodeDocument] = field(default_factory=list)
    lights: List[Dict[str, Any]] = field(default_factory=list)

    def __post_init__(self) -> None:
        if not self.name:
            raise DocumentError("scene name must not be empty")
        self.camera_position = _vec3(self.camera_position, "camera_position")
        self.camera_target = _vec3(self.camera_target, "camera_target")
        if not 0 < self.fov < 180:
            raise DocumentError("fov must be between 0 and 180 degrees")
        for light in self.lights:
            _validate_light(light)

    def add_node(self, node: NodeDocument) -> NodeDocument:
        if any(existing.id == node.id for existing in self.nodes):
            raise DocumentError(f"duplicate node id {node.id!r}")
        self.nodes.append(node)
        return node

    def remove_node(self, node_id: str) -> bool:
        before = len(self.nodes)
        self.nodes = [n for n in self.nodes if n.id != node_id]
        return len(self.nodes) != before

    def get_node(self, node_id: str) -> Optional[NodeDocument]:
        return next((n for n in self.nodes if n.id == node_id), None)

    def add_light(self, light: Dict[str, Any]) -> Dict[str, Any]:
        _validate_light(light)
        self.lights.append(dict(light))
        return self.lights[-1]

    def build_lights(self) -> List[Any]:
        return [_build_light(light) for light in self.lights]

    def build_camera(self, aspect: float) -> PerspectiveCamera:
        camera = PerspectiveCamera(self.fov, aspect, 0.5, 400.0, position=self.camera_position)
        return camera.look_at(Vec3(*self.camera_target))

    def build_renderer(self, width: int, height: int) -> SoftwareRenderer:
        renderer = SoftwareRenderer(width, height, self.build_camera(width / height))
        renderer.background = tuple(self.background)
        renderer.lights = self.build_lights()
        renderer.clear()
        for node in self.nodes:
            renderer.draw(MESHES[node.mesh](MESH_SIZES[node.mesh]), node.transform(), node.build_material())
        return renderer

    def to_dict(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "camera": {
                "position": list(self.camera_position),
                "target": list(self.camera_target),
                "fov": self.fov,
            },
            "background": list(self.background),
            "nodes": [node.to_dict() for node in self.nodes],
            "lights": [dict(light) for light in self.lights],
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "SceneDocument":
        if not isinstance(data, dict):
            raise DocumentError("scene document must be an object")
        camera = data.get("camera") or {}
        if not isinstance(camera, dict):
            raise DocumentError("camera must be an object")
        nodes = data.get("nodes") or []
        if not isinstance(nodes, list):
            raise DocumentError("nodes must be a list")
        lights = data.get("lights") or []
        if not isinstance(lights, list):
            raise DocumentError("lights must be a list")
        background = data.get("background") or (18, 20, 30, 255)
        if not isinstance(background, (list, tuple)) or len(background) not in (3, 4):
            raise DocumentError("background must be an RGB or RGBA list")
        return cls(
            name=str(data.get("name") or "scene"),
            camera_position=camera.get("position", (4.0, 2.8, 5.2)),
            camera_target=camera.get("target", (0.0, 0.5, 0.0)),
            fov=float(camera.get("fov", 55.0)),
            background=tuple(int(c) for c in background) + ((255,) if len(background) == 3 else ()),
            nodes=[NodeDocument.from_dict(item) for item in nodes],
            lights=[dict(item) for item in lights],
        )

    def save(self, path: str | Path) -> Path:
        target = Path(path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(self.to_dict(), indent=2, sort_keys=True) + "\n", encoding="utf-8")
        return target

    @classmethod
    def load(cls, path: str | Path) -> "SceneDocument":
        source = Path(path)
        try:
            data = json.loads(source.read_text(encoding="utf-8"))
        except FileNotFoundError as exc:
            raise DocumentError(f"scene not found: {source}") from exc
        except json.JSONDecodeError as exc:
            raise DocumentError(f"scene is not valid JSON: {exc}") from exc
        return cls.from_dict(data)


def _validate_light(data: Dict[str, Any]) -> None:
    if not isinstance(data, dict):
        raise DocumentError("each light must be an object")
    kind = data.get("type", "directional")
    if kind not in {"directional", "point", "spot"}:
        raise DocumentError(f"unknown light type {kind!r}")
    if kind == "directional" and "direction" not in data:
        raise DocumentError("directional light needs a direction")
    if kind in {"point", "spot"} and "position" not in data:
        raise DocumentError(f"{kind} light needs a position")


def _build_light(data: Dict[str, Any]) -> Any:
    kind = data.get("type", "directional")
    colour = tuple(data.get("colour", (255, 250, 240)))
    intensity = float(data.get("intensity", 1.0))
    if kind == "directional":
        return DirectionalLight(direction=Vec3(*data["direction"]), colour=colour, intensity=intensity)
    if kind == "point":
        return PointLight(position=Vec3(*data["position"]), colour=colour, intensity=intensity,
                          reach=float(data.get("reach", 8.0)))
    return SpotLight(position=Vec3(*data["position"]), direction=Vec3(*data.get("direction", (0, -1, 0))),
                     colour=colour, intensity=intensity, reach=float(data.get("reach", 12.0)))
